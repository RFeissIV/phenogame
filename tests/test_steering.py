class TestPayoffFormula:

    def test_basic_formula(self):
        f = PayoffFormula(outcome_col="yield_g")
        df = pd.DataFrame({"yield_g": [10.0, 20.0, 30.0]})
        result = f.compute(df)
        np.testing.assert_allclose(result, [10, 20, 30])

    def test_weighted_formula(self):
        f = PayoffFormula(
            outcome_col="yield_g", outcome_weight=1.0,
            quality_col="q", quality_weight=0.5,
            cost_col="c", cost_weight=0.3,
            risk_col="r", risk_weight=0.5,
        )
        df = pd.DataFrame({"yield_g": [10.0], "q": [0.8], "c": [2.0], "r": [0.4]})
        # U = 1.0*10 + 0.5*0.8 - 0.3*2.0 - 0.5*0.4 = 10 + 0.4 - 0.6 - 0.2 = 9.6
        result = f.compute(df)
        assert abs(result[0] - 9.6) < 1e-10

    def test_formula_str(self):
        f = PayoffFormula(
            outcome_col="yield_g", outcome_weight=1.0,
            quality_col="q", quality_weight=0.5,
            cost_col="c", cost_weight=0.3,
        )
        s = str(f)
        assert "yield_g" in s
        assert "q" in s
        assert "c" in s

    def test_formula_missing_optional_cols(self):
        f = PayoffFormula(
            outcome_col="yield_g", outcome_weight=1.0,
            quality_col="missing", quality_weight=0.5,
        )
        df = pd.DataFrame({"yield_g": [10.0]})
        result = f.compute(df)
        np.testing.assert_allclose(result, [10.0])


