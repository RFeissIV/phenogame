class TestBuildPayoffMatrixFromData:

    def test_categorical_data(self, simple_log):
        formula = PayoffFormula(outcome_col="outcome")
        pm, summary = build_payoff_matrix_from_data(
            simple_log, ["action"], "scenario", formula,
            discretize_actions=False, discretize_scenarios=False,
        )
        assert pm.matrix.shape == (2, 2)
        assert set(pm.strategy_labels) == {"A", "B"}
        assert set(pm.scenario_labels) == {"X", "Y"}

    def test_payoff_values_correct(self, simple_log):
        formula = PayoffFormula(outcome_col="outcome")
        pm, _ = build_payoff_matrix_from_data(
            simple_log, ["action"], "scenario", formula,
            discretize_actions=False, discretize_scenarios=False,
        )
        # A under X: mean(10, 12) = 11
        # A under Y: mean(8, 9) = 8.5
        # B under X: mean(7, 8) = 7.5
        # B under Y: mean(14, 15) = 14.5
        a_idx = pm.strategy_labels.index("A")
        b_idx = pm.strategy_labels.index("B")
        x_idx = pm.scenario_labels.index("X")
        y_idx = pm.scenario_labels.index("Y")
        assert abs(pm.matrix[a_idx, x_idx] - 11.0) < 1e-10
        assert abs(pm.matrix[a_idx, y_idx] - 8.5) < 1e-10
        assert abs(pm.matrix[b_idx, x_idx] - 7.5) < 1e-10
        assert abs(pm.matrix[b_idx, y_idx] - 14.5) < 1e-10

    def test_continuous_discretization(self, grow_log):
        formula = PayoffFormula(outcome_col="yield_g")
        pm, summary = build_payoff_matrix_from_data(
            grow_log, ["ppfd"], "temperature", formula,
            discretize_actions=True, discretize_scenarios=True,
            n_action_bins=3, n_scenario_bins=3,
        )
        assert pm.matrix.shape[0] >= 2
        assert pm.matrix.shape[1] >= 2
        assert summary.n_rows == len(grow_log)

    def test_multi_action_columns(self, grow_log):
        formula = PayoffFormula(outcome_col="yield_g")
        pm, summary = build_payoff_matrix_from_data(
            grow_log, ["ppfd", "irrigation_ml"], "temperature", formula,
            discretize_actions=True, discretize_scenarios=True,
            n_action_bins=2, n_scenario_bins=2,
        )
        assert pm.matrix.shape[0] >= 2
        assert summary.action_columns == ["ppfd", "irrigation_ml"]

    def test_data_summary_structure(self, simple_log):
        formula = PayoffFormula(outcome_col="outcome")
        _, summary = build_payoff_matrix_from_data(
            simple_log, ["action"], "scenario", formula,
            discretize_actions=False, discretize_scenarios=False,
        )
        assert isinstance(summary, DataSummary)
        assert summary.n_rows == 8
        assert "mean" in summary.outcome_stats
        assert "std" in summary.outcome_stats


