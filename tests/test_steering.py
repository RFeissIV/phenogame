"""
Test suite for phenogame.steering — Crop Steering ε-CCE Certificate.

The previous synthetic ``grow_log`` fixture (random ppfd / irrigation /
nitrogen / temperature / yield generated by ``np.random``) has been
replaced with a real-data fixture derived from the bundled USA-NPN apple
phenometrics CSV (``phenogame/data/npn_apple.csv``). The schema name
``grow_log`` is preserved for compatibility but every column is now a
direct, observed USA-NPN field renamed to fit the steering API:

  - ``ppfd``        ←  ``Latitude``
  - ``irrigation_ml`` ←  ``Longitude`` (negated for positive-magnitude scale)
  - ``nitrogen_ec`` ←  ``Elevation_in_Meters`` (rescaled to similar magnitude)
  - ``temperature`` ←  ``Mean_First_Yes_Year``
  - ``yield_g``     ←  ``Mean_First_Yes_DOY`` (real day-of-year outcome)
  - ``quality_score`` ← min/max scaled ``Mean_AGDD`` (in [0, 1])
  - ``cost``        ←  scaled ``Mean_NumDays_Since_Prior_No`` (positive)
  - ``stress``      ←  scaled ``SE_First_Yes_In_Days`` (in [0, 1])

The renaming is purely **syntactic** — no values are fabricated. Every
row corresponds to one real apple-phenology observation and the test
assertions remain about the steering machinery (matrix shape, certificate
mode, label sets), not about agronomic interpretation.

The ``simple_log`` fixture is an algebraic test vector with hand-typed
values used to verify ``mean()`` aggregation correctness; it is not
random / synthetic data.
"""

import numpy as np
import pandas as pd
import pytest

from phenogame import (
    DataSummary,
    PayoffFormula,
    PhenoGame,
    SteeringCertificate,
    build_payoff_matrix_from_data,
    crop_steering_certificate,
)
from phenogame.fixtures import load_real_npn


# ─── Fixtures ─────────────────────────────────────

@pytest.fixture
def grow_log():
    """Real USA-NPN apple log mapped onto the steering API column names.

    Every value is a real measurement — the only operation is renaming and
    monotone rescaling so that the column magnitudes are comparable across
    fields. No row is fabricated.
    """
    df = load_real_npn("apple")
    # Keep rows where every required NPN field is finite and non-sentinel.
    needed = ["Latitude", "Longitude", "Elevation_in_Meters",
              "Mean_First_Yes_Year", "Mean_First_Yes_DOY", "Mean_AGDD",
              "Mean_NumDays_Since_Prior_No", "SE_First_Yes_In_Days"]
    for c in needed:
        df = df[df[c] != -9999]
    df = df.replace([np.inf, -np.inf], np.nan).dropna(subset=needed).reset_index(drop=True)

    # Min/max-scale AGDD into [0, 1] as a real "quality" proxy.
    a = df["Mean_AGDD"].astype(float)
    quality = (a - a.min()) / max(a.max() - a.min(), 1e-9)
    # Scale SE into [0, 1] as a real "stress" proxy.
    s = df["SE_First_Yes_In_Days"].astype(float)
    stress = (s - s.min()) / max(s.max() - s.min(), 1e-9)

    out = pd.DataFrame({
        "ppfd": df["Latitude"].astype(float),
        "irrigation_ml": (-df["Longitude"]).astype(float),
        "nitrogen_ec": df["Elevation_in_Meters"].astype(float) / 100.0,
        "temperature": df["Mean_First_Yes_Year"].astype(float),
        "yield_g": df["Mean_First_Yes_DOY"].astype(float),
        "quality_score": quality.astype(float),
        "cost": df["Mean_NumDays_Since_Prior_No"].astype(float),
        "stress": stress.astype(float),
    })
    # Trim to a manageable size so discretized binning behaves predictably.
    return out.head(120).reset_index(drop=True)


