class TestCropSteeringCertificate:

    def test_basic_certificate(self, simple_log):
        cert = crop_steering_certificate(
            data=simple_log,
            action_columns=["action"],
            scenario_column="scenario",
            outcome_column="outcome",
            mode="provable",
            iterations=1000,
            seed=42,
            discretize_actions=False,
            discretize_scenarios=False,
        )
        assert isinstance(cert, SteeringCertificate)
        assert cert.recommended_strategy in ["A", "B"]
        assert cert.certificate.mode == "provable"

    def test_full_certificate_with_weights(self, grow_log):
        cert = crop_steering_certificate(
            data=grow_log,
            action_columns=["ppfd", "irrigation_ml"],
            scenario_column="temperature",
            outcome_column="yield_g",
            quality_column="quality_score",
            cost_column="cost",
            risk_column="stress",
            payoff_weights={"outcome": 1.0, "quality": 0.5, "cost": 0.3, "risk": 0.5},
            mode="provable",
            iterations=1000,
            seed=42,
            n_action_bins=2,
            n_scenario_bins=2,
        )
        assert isinstance(cert, SteeringCertificate)
        assert cert.certificate.is_certified or cert.certificate.cce_gap >= 0

    def test_empirical_mode(self, simple_log):
        cert = crop_steering_certificate(
            data=simple_log,
            action_columns=["action"],
            scenario_column="scenario",
            outcome_column="outcome",
            mode="empirical",
            iterations=1000,
            tau=1.0,
            seed=42,
            discretize_actions=False,
            discretize_scenarios=False,
        )
        assert cert.certificate.mode == "empirical"

    def test_invalid_mode(self, simple_log):
        with pytest.raises(ValueError, match="mode"):
            crop_steering_certificate(
                data=simple_log,
                action_columns=["action"],
                scenario_column="scenario",
                outcome_column="outcome",
                mode="bogus",
                discretize_actions=False,
                discretize_scenarios=False,
            )

    def test_missing_column(self, simple_log):
        with pytest.raises(ValueError, match="Missing"):
            crop_steering_certificate(
                data=simple_log,
                action_columns=["nonexistent"],
                scenario_column="scenario",
                outcome_column="outcome",
            )

    def test_summary_renders(self, simple_log):
        cert = crop_steering_certificate(
            data=simple_log,
            action_columns=["action"],
            scenario_column="scenario",
            outcome_column="outcome",
            iterations=500,
            seed=42,
            discretize_actions=False,
            discretize_scenarios=False,
        )
        s = cert.summary()
        assert "CROP STEERING" in s
        assert "PAYOFF FORMULA" in s
        assert "RECOMMENDATION" in s
        assert "LIMITATIONS" in s
        assert "certified ε-CCE" in s.lower() or "ε-CCE" in s

    def test_phenogame_static_method(self, simple_log):
        cert = PhenoGame.crop_steering_certificate(
            data=simple_log,
            action_columns=["action"],
            scenario_column="scenario",
            outcome_column="outcome",
            iterations=500,
            seed=42,
            discretize_actions=False,
            discretize_scenarios=False,
        )
        assert isinstance(cert, SteeringCertificate)

    def test_fit_driver(self, grow_log):
        cert = crop_steering_certificate(
            data=grow_log,
            action_columns=["ppfd"],
            scenario_column="temperature",
            outcome_column="yield_g",
            iterations=500,
            seed=42,
            n_action_bins=2,
            n_scenario_bins=2,
            fit_driver_col="ppfd",
        )
        assert cert.fit_report is not None
        assert cert.fit_report.n_converged > 0

    def test_consensus_flag(self, simple_log):
        cert = crop_steering_certificate(
            data=simple_log,
            action_columns=["action"],
            scenario_column="scenario",
            outcome_column="outcome",
            iterations=500,
            seed=42,
            discretize_actions=False,
            discretize_scenarios=False,
        )
        assert isinstance(cert.consensus, bool)

    def test_csv_path_input(self, simple_log, tmp_path):
        csv_path = tmp_path / "test.csv"
        simple_log.to_csv(csv_path, index=False)
        cert = crop_steering_certificate(
            data=str(csv_path),
            action_columns=["action"],
            scenario_column="scenario",
            outcome_column="outcome",
            iterations=500,
            seed=42,
            discretize_actions=False,
            discretize_scenarios=False,
        )
        assert isinstance(cert, SteeringCertificate)
